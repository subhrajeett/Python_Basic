#for_loop used over a sequence 
#Dont need to manage counter manually like while
 
for i in range(1,11):
    #last digit excluded from range
    print(i,end=" ")
print("Ok")

#steps in for loops
for i in range(1,10,3):
    print(i,end=" ")
print("Ok")

#desc for loop
for i in range(10,0,-1):
    print(i,end=" ")
print("Ok")
